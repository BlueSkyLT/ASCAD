#!/usr/bin/env python3
"""Generate the paper's result tables from the experiment JSONs (no number is typed by hand).

Sources (all decoded with ASCAD_PI_ROUTING=raw, i.e. MS23's independent-pi decoding, on the first
5,000 ASCADv2 attack traces):
  GPAM/artifacts/crop34/cmp_*_raw.json, crop34_*_verify_raw.json   compact_verify.py outputs
  GPAM/artifacts/crop34/ge_ms23_style.json                         500-attack GE (t042_compare_400k.py ge)
Missing sources render as "pending", so the tables can be rebuilt as runs land.

Usage:  /home/lantian/miniconda3/envs/py10/bin/python paper/tches/scripts/make_tables.py
"""

import json
import os

REPO = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..", ".."))
A = os.path.join(REPO, "GPAM", "artifacts", "crop34")
OUT = os.path.join(REPO, "paper", "tches", "tables")

# row label, params (M), recipe note, compact_verify json, label in ge_ms23_style.json
ROWS = [
    ("MultiResNet (reprod.), best", "137.4", "MS23 recipe", "cmp_mrn400k_s1_best_raw.json", "MultiResNet s1 best"),
    ("MultiResNet (reprod.), last", "137.4", "MS23 recipe", "cmp_mrn400k_s1_last_raw.json", "MultiResNet s1 last"),
    ("MultiResNet (reprod.) s2, best", "137.4", "MS23 recipe", "cmp_mrn400k_s2_best_raw.json", "MRN s2 best"),
    ("MultiResNet (reprod.) s2, last", "137.4", "MS23 recipe", "cmp_mrn400k_s2_last_raw.json", "MRN s2 last"),
    ("MultiResNet + $w_C$, $\\mathcal{L}_{\\mathrm{dec}}$, best", "137.4", "+ our losses",
     "cmp_mrn400k_cw05dec_s1_best_raw.json", "MRN+wC0.5+dec s1 best"),
    ("MultiResNet + $w_C$, $\\mathcal{L}_{\\mathrm{dec}}$, last", "137.4", "+ our losses",
     "cmp_mrn400k_cw05dec_s1_last_raw.json", "MRN+wC0.5+dec s1 last"),
    ("Compact (plain), best", "15.65", "MS23 recipe", "cmp_compact400k_plain_s1_best_raw.json", "Compact plain s1 best"),
    ("Compact (plain), last", "15.65", "MS23 recipe", "cmp_compact400k_plain_s1_last_raw.json", "Compact plain s1 last"),
    ("Compact s1, best", "15.65", "+ our losses", "cmp_compact400k_s1_best_raw.json", "Compact s1 best"),
    ("Compact s1, last", "15.65", "+ our losses", "cmp_compact400k_s1_last_raw.json", "Compact s1 last"),
    ("Compact s2, best", "15.65", "+ our losses", "cmp_compact400k_s2_best_raw.json", "Compact s2 best"),
    ("Compact s2, last", "15.65", "+ our losses", "cmp_compact400k_s2_last_raw.json", "Compact s2 last"),
    ("GPAM, paper LR", "6.11", "GPAM recipe", "crop34_paper_seed0_verify_raw.json", None),
    ("GPAM, LR $10^{-3}$", "6.11", "GPAM recipe", "crop34_lr1e-3_seed0_verify_raw.json", "GPAM lr1e-3 seed0"),
    ("GPAM, LR $10^{-3}$ + sub\\_avg", "6.11", "GPAM recipe", "crop34_lr1e-3_subavg_seed0_verify_raw.json",
     "GPAM lr1e-3 sub_avg seed0"),
]
PENDING = "\\textit{pending}"


def load(name):
    p = os.path.join(A, name)
    return json.load(open(p)) if os.path.exists(p) else None


def fmt(v, nd=0):
    if v is None:
        return "--"
    return f"{v:.{nd}f}" if nd else f"{int(round(v))}"


def main_table(ge):
    lines = [
        "% generated by paper/tches/scripts/make_tables.py -- do not edit by hand",
        "\\begin{tabular}{llrrrrrr}",
        "\\toprule",
        "Model & Params (M) & 16/16 & median $z$ & GE$<1$ & GE$<0.5$ & GE$=0$ & MTD \\\\",
        "\\midrule",
        "MS23 MultiResNetSCA-1~\\cite{MS23} & 137.4 & yes & -- & $\\approx$60 & -- & -- & -- \\\\",
    ]
    for label, params, _, vj, gl in ROWS:
        v = load(vj)
        if v is None:
            lines.append(f"{label} & {params} & \\multicolumn{{6}}{{c}}{{{PENDING}}} \\\\")
            continue
        s = v["decoders"]["as_trained"]["summary"]
        ok = "yes" if s["n_rank0_and_not_flat"] == 16 else f"{s['n_rank0_and_not_flat']}/16"
        g = (ge or {}).get(gl, {}).get("full_key") if gl else None
        if g is None and gl:
            gcells = f"\\multicolumn{{4}}{{c}}{{{PENDING}}}"
        elif g is None:
            gcells = "-- & -- & -- & --"
        else:
            gcells = f"{fmt(g['ge_lt1'])} & {fmt(g['ge_lt05'])} & {fmt(g['ge_eq0'])} & {fmt(g['mtd_worst_byte'], 1)}"
        lines.append(f"{label} & {params} & {ok} & {s['median_z']:+.2f} & {gcells} \\\\")
    lines += ["\\bottomrule", "\\end{tabular}"]
    return "\n".join(lines) + "\n"


def head_table():
    lines = [
        "% generated by paper/tches/scripts/make_tables.py -- do not edit by hand",
        "\\begin{tabular}{lrrrrr}",
        "\\toprule",
        "Model & $\\alpha$ (\\%) & $\\beta$ (\\%) & $C$ (\\%) & $C$ gain (nats) & $\\pi$ (\\%) \\\\",
        "\\midrule",
        "MS23 MultiResNetSCA-1 (Table 2 of~\\cite{MS23}) & 99.2 & 21.1 & 1.6 & -- & 88.9 \\\\",
    ]
    for label, _, _, vj, _ in ROWS:
        if "last" in label:
            continue
        v = load(vj)
        if v is None:
            lines.append(f"{label} & \\multicolumn{{5}}{{c}}{{{PENDING}}} \\\\")
            continue
        h = v["head_metrics"]
        lines.append(f"{label} & {100 * h['alpha']['top1_acc']:.2f} & {100 * h['beta']['top1_acc']:.2f} & "
                     f"{100 * h['C_mean_top1']:.2f} & {h['C_mean_gain']:+.3f} & {100 * h['pi_element_top1']:.2f} \\\\")
    lines += ["\\bottomrule", "\\end{tabular}"]
    return "\n".join(lines) + "\n"


def main():
    os.makedirs(OUT, exist_ok=True)
    g = load("ge_ms23_style.json")
    ge = g["models"] if g else None
    for name, text in (("main_results.tex", main_table(ge)), ("head_accuracy.tex", head_table())):
        with open(os.path.join(OUT, name), "w") as f:
            f.write(text)
        print(f"wrote {os.path.join(OUT, name)}")


if __name__ == "__main__":
    main()
